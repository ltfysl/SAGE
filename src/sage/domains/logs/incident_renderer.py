"""Incident report renderer for SAGE Incident Lens.

Produces developer-facing Markdown incident reports with:
- Incident Summary
- Event Categories with evidence line references
- Top Exceptions with counts and timestamps
- Condensed Timeline
- Evidence Highlights (truncated to 240 chars)
- Likely Impact (deterministically inferred)
- Suggested Investigation Checklist
"""

from __future__ import annotations
from pathlib import Path
from datetime import datetime
from collections import Counter


def render_markdown_report(state: dict, ops: list[dict] = None, output_path: Path = None) -> str:
    """Render a complete SAGE Incident Lens Markdown report.

    Args:
        state: State dict from IncidentState.to_dict()
        ops: Raw operation list (for evidence lines)
        output_path: Optional path to save report
    """
    if ops is None:
        ops = []

    lines = []
    lines.append("# SAGE Incident Lens — Incident Report")
    lines.append("")
    lines.append(f"**Generated**: {datetime.now().isoformat()}")
    lines.append(f"**Parser mode**: deterministic")
    lines.append(f"**Evidence-bound**: yes")
    lines.append("")

    # ── 1. Incident Summary ──
    lines.append("## 1. Incident Summary")
    lines.append("")
    lines.append(f"| Metric | Value |")
    lines.append(f"|--------|-------|")
    lines.append(f"| First error | {_val(state.get('first_error_at'))} |")
    lines.append(f"| Last error | {_val(state.get('last_error_at'))} |")
    lines.append(f"| Time range | {_time_range(state.get('first_error_at'), state.get('last_error_at'))} |")
    lines.append(f"| Total incident events | {state.get('total_errors', 0)} |")
    lines.append(f"| Top exception | `{_val(state.get('top_exception'))}` |")
    lines.append(f"| Top category | {_top_category(state.get('error_count_by_type', {}))} |")
    lines.append(f"| Affected components | {_val(', '.join(state.get('affected_components', [])) or 'laravel')} |")
    lines.append(f"| Severity estimate | {_severity(state)} |")
    lines.append("")

    # ── 2. Event Categories ──
    lines.append("## 2. Event Categories")
    lines.append("")
    lines.append("| Category | Count | First | Last | Evidence |")
    lines.append("|----------|-------|-------|------|----------|")
    cat_data = _build_category_data(ops)
    for cat_name, data in sorted(cat_data.items(), key=lambda x: -x[1]['count']):
        ev = _truncate(data.get('evidence', ''), 60)
        lines.append(f"| {cat_name} | {data['count']} | {data['first']} | {data['last']} | {ev} |")
    lines.append("")

    # ── 3. Top Exceptions ──
    lines.append("## 3. Top Exceptions")
    lines.append("")
    exc_data = _build_exception_data(ops)
    rank = 0
    for exc_class, data in sorted(exc_data.items(), key=lambda x: -x[1]['count'])[:10]:
        rank += 1
        lines.append(f"**{rank}. `{exc_class}`** — {data['count']} occurrences")
        lines.append(f"    First seen: {data['first']}")
        lines.append(f"    Last seen:  {data['last']}")
        lines.append(f"    Likely category: {data['category']}")
        ev = _truncate(data.get('evidence', ''), 200)
        lines.append(f"    Evidence: _{ev}_")
        lines.append("")

    # ── 4. Condensed Timeline ──
    lines.append("## 4. Condensed Timeline")
    lines.append("")
    timeline_events = _build_timeline(ops)
    for event in timeline_events:
        lines.append(f"- `{event['timestamp']}` **[{event['op']}]** {event['message']}")
        lines.append(f"  Evidence: {_truncate(event.get('evidence_span', ''), 200)}")
    if not timeline_events:
        lines.append("(No events to display)")
    lines.append("")

    # ── 5. Evidence Highlights ──
    lines.append("## 5. Evidence Highlights")
    lines.append("")
    highlights = _build_evidence_highlights(ops)
    for h in highlights:
        lines.append(f"- **[{h['op']}]** `{h['timestamp']}`")
        lines.append(f"  {h['message'][:200]}")
        if h.get('file'):
            lines.append(f"  File: {h['file']}" + (f":{h['line']}" if h.get('line') else ""))
        lines.append("")

    # ── 6. Likely Impact ──
    lines.append("## 6. Likely Impact")
    lines.append("")
    impact = _infer_impact(ops)
    for area, detail in impact.items():
        lines.append(f"- **{area}**: {detail}")
    lines.append("")

    # ── 7. Suggested Investigation Checklist ──
    lines.append("## 7. Suggested Investigation Checklist")
    lines.append("")
    checklist = _build_checklist(cat_data, exc_data)
    for item in checklist:
        lines.append(f"- [ ] {item}")
    lines.append("")

    # ── Footer ──
    lines.append("---")
    lines.append("*Generated by SAGE Incident Lens — deterministic, evidence-bound analysis.*")
    lines.append("*Private log content is not stored in git.*")

    md = "\n".join(lines)
    if output_path:
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(md)
    return md


def render_incident_report(state: dict) -> str:
    """Render plain-text incident summary for terminal output."""
    lines = []
    lines.append("=" * 60)
    lines.append("SAGE Incident Lens — Laravel Log Analysis")
    lines.append("=" * 60)
    lines.append("")
    lines.append(f"First error:  {state.get('first_error_at', 'N/A')}")
    lines.append(f"Last error:   {state.get('last_error_at', 'N/A')}")
    lines.append(f"Total errors: {state.get('total_errors', 0)}")
    lines.append(f"Top exception: {state.get('top_exception', 'N/A')}")
    lines.append(f"Components:   {', '.join(state.get('affected_components', [])) or 'laravel'}")
    lines.append("")
    lines.append("Error Count by Type:")
    for op_type, count in sorted(state.get("error_count_by_type", {}).items()):
        lines.append(f"  {op_type}: {count}")
    lines.append("")

    for section, key in [
        ("Mail Failures", "mail_failures"),
        ("Queue Failures", "queue_failures"),
        ("Database Errors", "database_errors"),
        ("Failed Jobs", "failed_jobs"),
    ]:
        items = state.get(key, [])
        if items:
            lines.append(f"{section} ({len(items)}):")
            for item in items[:5]:
                lines.append(f"  {item['timestamp']}: {_truncate(item.get('message', ''), 100)}")
            lines.append("")

    lines.append("Timeline (last 20 events):")
    for event in state.get("timeline", []):
        lines.append(f"  {event['timestamp']} [{event['op']}] {_truncate(event.get('message', ''), 100)}")

    return "\n".join(lines)


# ── Helpers ──

def _val(v) -> str:
    if v is None:
        return "N/A"
    return str(v)


def _truncate(text: str, max_len: int = 240) -> str:
    if not text:
        return ""
    if len(text) <= max_len:
        return text
    return text[:max_len] + "…"


def _time_range(first: str | None, last: str | None) -> str:
    if not first or not last:
        return "N/A"
    try:
        from datetime import datetime as dt
        f = dt.strptime(first, "%Y-%m-%d %H:%M:%S")
        l = dt.strptime(last, "%Y-%m-%d %H:%M:%S")
        diff = l - f
        hours = diff.total_seconds() / 3600
        if hours < 1:
            return f"{int(diff.total_seconds() // 60)} minutes"
        elif hours < 24:
            return f"{hours:.1f} hours"
        else:
            return f"{hours / 24:.1f} days ({hours:.1f} hours)"
    except:
        return f"{first} → {last}"


def _top_category(counts: dict) -> str:
    if not counts:
        return "N/A"
    top = max(counts, key=counts.get)
    return f"{top} ({counts[top]} events)"


def _severity(state: dict) -> str:
    total = state.get('total_errors', 0)
    counts = state.get('error_count_by_type', {})
    db = counts.get('DATABASE_ERROR', 0)
    mail = counts.get('MAIL_FAILURE', 0)
    queue = counts.get('QUEUE_FAILURE', 0)
    if total == 0:
        return "None"
    if db + mail + queue > total * 0.5 and total > 20:
        return "🔴 Critical — multiple service failures"
    if total > 50:
        return "🟠 High — high error volume"
    if total > 10:
        return "🟡 Medium — moderate incident"
    return "🟢 Low"


def _build_category_data(ops: list[dict]) -> dict:
    """Aggregate operations by category with first/last timestamps and evidence."""
    data = {}
    for op in ops:
        cat = op.get('op', 'UNKNOWN')
        ts = op.get('timestamp', '')
        ev = op.get('evidence', {}).get('span', '')[:240]
        msg = op.get('message', '')[:200]
        if cat not in data:
            data[cat] = {'count': 0, 'first': ts, 'last': ts, 'evidence': ev, 'message': msg}
        data[cat]['count'] += 1
        if ts < data[cat]['first']:
            data[cat]['first'] = ts
        if ts > data[cat]['last']:
            data[cat]['last'] = ts
    return data


def _build_exception_data(ops: list[dict]) -> dict:
    """Aggregate by exception class."""
    data = {}
    for op in ops:
        exc = op.get('exception', '') or 'Unknown'
        ts = op.get('timestamp', '')
        ev = op.get('evidence', {}).get('span', '')[:240]
        if exc not in data:
            data[exc] = {'count': 0, 'first': ts, 'last': ts, 'evidence': ev, 'category': op.get('op', '')}
        data[exc]['count'] += 1
        if ts < data[exc]['first']:
            data[exc]['first'] = ts
        if ts > data[exc]['last']:
            data[exc]['last'] = ts
    return data


def _build_timeline(ops: list[dict]) -> list[dict]:
    """Build a condensed timeline — first occurrence per category + spikes + recovery."""
    seen_categories = set()
    timeline = []
    counts = Counter()
    recovery_ops = []

    for op in ops:
        cat = op.get('op', '')
        counts[cat] += 1
        # First occurrence per category
        if cat not in seen_categories:
            seen_categories.add(cat)
            timeline.append({
                'timestamp': op.get('timestamp', ''),
                'op': cat,
                'message': f"First {cat}: {_truncate(op.get('message', ''), 80)}",
                'evidence_span': op.get('evidence', {}).get('span', '')[:240],
            })
        # Recovery events
        if cat == 'RECOVERY_EVENT':
            recovery_ops.append(op)

    # Add recovery events
    for op in recovery_ops[:5]:
        timeline.append({
            'timestamp': op.get('timestamp', ''),
            'op': 'RECOVERY_EVENT',
            'message': op.get('message', '')[:120],
            'evidence_span': op.get('evidence', {}).get('span', '')[:240],
        })

    # Sort by timestamp
    timeline.sort(key=lambda x: x['timestamp'])
    return timeline[:30]


def _build_evidence_highlights(ops: list[dict]) -> list[dict]:
    """Pick representative evidence examples per category."""
    highlights = []
    seen_cats = set()
    for op in ops:
        cat = op.get('op', '')
        if cat not in seen_cats:
            seen_cats.add(cat)
            highlights.append({
                'op': cat,
                'timestamp': op.get('timestamp', ''),
                'message': op.get('message', ''),
                'file': op.get('file', ''),
                'line': op.get('line_number', 0),
            })
    return highlights[:10]


def _infer_impact(ops: list[dict]) -> dict:
    """Deterministically infer likely impacted areas from categories and messages."""
    impact = {}
    seen_components = set()
    for op in ops:
        msg = op.get('message', '')
        exc = op.get('exception', '') or ''
        raw = op.get('evidence', {}).get('span', '')
        cat = op.get('op', '')

        if 'SCORM' in msg or 'scorm' in raw.lower() or 'CourseProgress' in raw or 'ScormCommit' in raw:
            if 'scorm' not in seen_components:
                seen_components.add('scorm')
                impact['SCORM / course progress'] = 'Evidence from stacktrace shows SCORM commit and course progress services affected'

        if 'CertificateMail' in raw or 'SendCertificateMail' in raw or cat == 'MAIL_FAILURE':
            if 'mail' not in seen_components:
                seen_components.add('mail')
                impact['Certificate mail delivery'] = 'Mail transport failures and SendCertificateMail job errors detected'

        if 'Queue' in exc or 'queue' in msg.lower() or 'MaxAttemptsExceeded' in exc or cat == 'QUEUE_FAILURE':
            if 'queue' not in seen_components:
                seen_components.add('queue')
                impact['Background jobs / queue worker'] = 'Queue job failures and max attempt exceeded errors suggest queue worker issues'

        if '403' in msg or 'Auth' in exc or 'Unauthorized' in msg or cat == 'AUTH_ERROR':
            if 'auth' not in seen_components:
                seen_components.add('auth')
                impact['Manager / admin access'] = '403 and authentication errors suggest access control issues'

        if '500' in msg or 'Server Error' in msg or 'HttpException' in exc or cat == 'HTTP_ERROR':
            if 'api' not in seen_components:
                seen_components.add('api')
                impact['API endpoints'] = '500 Internal Server Errors detected on API endpoints'

        if 'ViewException' in exc or 'ParseError' in exc:
            if 'view' not in seen_components:
                seen_components.add('view')
                impact['View rendering / PHP syntax'] = f'{exc} suggests deployment or syntax issues in view files'

    if not impact:
        impact['General application health'] = 'Error patterns suggest broad application issues — review individual categories'

    return impact


def _build_checklist(cat_data: dict, exc_data: dict) -> list[str]:
    """Generate deterministic investigation checklist based on detected categories."""
    items = []

    if 'DATABASE_ERROR' in cat_data:
        items.append("Check database connectivity and credentials")
        items.append("Check database server availability during incident window")
        items.append("Inspect failed queries around first error timestamp")
        items.append("Check for schema changes or migration issues")
        if 'Illuminate\\\\Database\\\\QueryException' in exc_data:
            items.append("Review QueryException stack traces for specific failed queries")

    if 'MAIL_FAILURE' in cat_data:
        items.append("Verify SMTP host, port, and connectivity from application server")
        items.append("Check mail service credentials and provider status")
        items.append("Inspect failed mail jobs in queue")

    if 'QUEUE_FAILURE' in cat_data or 'FAILED_JOB' in cat_data:
        items.append("Check queue worker processes — restart if not running")
        items.append("Inspect failed_jobs table for stuck jobs")
        items.append("Review queue worker timeout and retry settings")

    if 'AUTH_ERROR' in cat_data or 'HTTP_ERROR' in cat_data:
        items.append("Check web server and application access logs")
        items.append("Verify middleware and authentication configuration")
        items.append("Check for recent deployment or configuration changes")

    if 'ParseError' in exc_data or 'ErrorException' in exc_data:
        items.append("Check recent deployments around first occurrence timestamp")
        items.append("Inspect the files and lines referenced in evidence")
        items.append("Verify PHP syntax and clear cached compiled views")

    if 'RECOVERY_EVENT' in cat_data:
        items.append("Verify recovery actions were effective — monitor for recurrence")
    else:
        items.append("No recovery events detected — manual intervention may be required")

    items.append("Review full timeline for correlation between error categories")
    return items
